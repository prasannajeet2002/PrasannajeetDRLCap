"""Final tables and timelines for the f2 queue (run_f2.sh).

Same method as analyze_f1.py (paper method, paper comparisons only). f2 is
the f1 reference configuration with one setting changed (minimum frequency
cap 1800 -> 2100 MHz) and the trained seed chosen on the validation
programs; see F2_CHANGES.md.

Main comparison = eval_main_a_f2_* (repeats 1-5) + eval_main_b_f2_*
(repeats 6-10). Runs that shared the GPU with another job (gpu_shared = 1)
are dropped.

Usage: python analyze_f2.py   -> results/final_f2/
"""

import os

import analyze_f1 as A

A.OUT = os.path.join(A.RES, "final_f2")


def clean(d):
    rows = A.runs_of(d)
    kept = [r for r in rows if r.get("gpu_shared", "0") != "1"]
    return kept, len(rows) - len(kept)


def mean_caps(rows, policies, f):
    f.write("\nMean frequency cap set by the agent, MHz (range 2100-2745)\n\n")
    f.write("| Program | " + " | ".join(policies) + " |\n")
    f.write("|---" * (len(policies) + 1) + "|\n")
    for p in sorted({r["workload"] for r in rows}):
        cells = []
        for pol in policies:
            c = [float(r["mean_cap_mhz"]) for r in rows
                 if r["workload"] == p and r["policy"] == pol]
            cells.append(f"{sum(c) / len(c):.0f}")
        f.write(f"| {p} | " + " | ".join(cells) + " |\n")


def main():
    os.makedirs(A.OUT, exist_ok=True)
    main_a, da = clean(A.one("eval_main_a_f2_2*"))
    main_b, db = clean(A.one("eval_main_b_f2_2*"))
    val, dv = clean(A.one("eval_val_f2_2*"))
    frozen, df = clean(A.one("eval_frozen_f2_2*"))
    main_rows = main_a + main_b

    path = os.path.join(A.OUT, "RESULTS_F2.md")
    with open(path, "w") as f:
        f.write("# DRLCap faithful reproduction (f2): final results\n\n"
                "Generated by `analyze_f2.py`. Paper method: mean over "
                "repeats per program, ratio to the NVIDIA default, geometric "
                "mean over the 10 Table II programs. RTX 4070 Ti. Paper "
                "(V100S) for DRLCap: 22 % energy, 3 % perf loss, 20 % EDP; "
                "COORD 25/5/21; RL 5/1/4. f1 result for DRLCap: 14.2 / 4.0 "
                "/ 10.8.\n\n"
                f"Runs dropped because the GPU was shared: main {da + db}, "
                f"validation {dv}, frozen {df}.\n")
        seeds = [f"seed{i}" for i in range(5)]
        A.table("Seed selection on the validation programs (3 repeats)",
                val, seeds, f)
        f.write("\nThe seed with the best validation EDP (seed 4) is the "
                "`drlcap` row below; `drlcap_seed0` is an unselected seed, "
                "shown for transparency.\n")
        pols = ["drlcap", "drlcap_power", "drlcap_hybrid", "coord", "rl"]
        pp = A.table("Main comparison (10 repeats)", main_rows,
                     pols + ["drlcap_seed0"], f)
        A.per_program_table(pp, pols + ["drlcap_seed0"], f)
        A.table("Main comparison, repeats 1-5 only", main_a, pols, f)
        A.table("Main comparison, repeats 6-10 only", main_b, pols, f)
        A.table("Frozen network, no online learning (3 repeats)", frozen,
                ["drlcap_frozen"], f)
        mean_caps(main_rows, ["drlcap", "drlcap_seed0"], f)
        A.timelines(A.one("eval_main_a_f2_2*"), f)
    print(open(path).read())


if __name__ == "__main__":
    main()
